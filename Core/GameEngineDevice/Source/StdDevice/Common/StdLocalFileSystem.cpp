// GeneralsX @bugfix felipebraz 23/03/2026 Asset root fallback path for loose file lookups.
// On Linux/macOS the game binary's cwd and the data directory (asset root, CNC_GENERALS_ZH_PATH) are separate.
// The StdBIGFileSystem sets this after resolving the primary asset directory so that relative paths like
// "Data\Scripts\SkirmishScripts.scb" can be found in the asset root when the cwd lookup fails.
static std::filesystem::path s_assetFallbackPath;

// ---------------------------------------------------------------------------
// r042: game data lives INSIDE the APK (assets/GeneralsZH/...). Nothing is
// unpacked: every read that is not found on disk is served from the APK via a
// reader installed by SDL3Main (SDL_IOFromFile -> AAssetManager). The list of
// files comes from assets/GeneralsZH/_apkindex.txt generated by Gradle.
// ---------------------------------------------------------------------------
bool (*g_gxApkRead)(const char *path, char **data, size_t *size) = nullptr;

struct GxApkEntry { std::string real; size_t size; };
static std::unordered_map<std::string, GxApkEntry> *s_gxApk = nullptr;

static std::string gxApkNorm(const char *p)
{
	std::string s;
	if (p == nullptr) return s;
	s.reserve(strlen(p));
	for (const char *c = p; *c; ++c) {
		char ch = *c;
		if (ch == '\\') ch = '/';
		if (ch >= 'A' && ch <= 'Z') ch = (char)(ch - 'A' + 'a');
		if (ch == '/' && !s.empty() && s.back() == '/') continue;
		s.push_back(ch);
	}
	while (s.size() >= 2 && s[0] == '.' && s[1] == '/') s.erase(0, 2);
	while (!s.empty() && s[0] == '/') s.erase(0, 1);
	return s;
}

static void gxApkLoadIndex()
{
	if (s_gxApk != nullptr || g_gxApkRead == nullptr) return;
	s_gxApk = new std::unordered_map<std::string, GxApkEntry>();
	char *d = nullptr; size_t n = 0;
	if (!g_gxApkRead("GeneralsZH/_apkindex.txt", &d, &n) || d == nullptr) {
		fprintf(stderr, "GX APK: _apkindex.txt not found in APK\n");
		return;
	}
	std::string all(d, n);
	free(d);
	size_t pos = 0;
	while (pos < all.size()) {
		size_t eol = all.find('\n', pos);
		if (eol == std::string::npos) eol = all.size();
		std::string line = all.substr(pos, eol - pos);
		pos = eol + 1;
		if (!line.empty() && line.back() == '\r') line.pop_back();
		size_t tab = line.find('\t');
		if (tab == std::string::npos || tab == 0) continue;
		GxApkEntry e;
		e.real = line.substr(0, tab);
		e.size = (size_t)strtoull(line.c_str() + tab + 1, nullptr, 10);
		(*s_gxApk)[gxApkNorm(e.real.c_str())] = e;
	}
	fprintf(stderr, "GX APK: %zu game files available from the APK\n", s_gxApk->size());
}

static const GxApkEntry *gxApkFind(const char *name)
{
	gxApkLoadIndex();
	if (s_gxApk == nullptr) return nullptr;
	auto it = s_gxApk->find(gxApkNorm(name));
	return it == s_gxApk->end() ? nullptr : &it->second;
}

static File *gxApkOpen(const char *name)
{
	const GxApkEntry *e = gxApkFind(name);
	if (e == nullptr) return nullptr;
	char *d = nullptr; size_t n = 0;
	std::string full = std::string("GeneralsZH/") + e->real;
	if (!g_gxApkRead(full.c_str(), &d, &n) || d == nullptr) return nullptr;
	RAMFile *rf = newInstance(RAMFile);
	if (!rf->openFromBuffer(name, d, (Int)n)) {
		deleteInstance(rf);
		free(d);
		return nullptr;
	}
	free(d);
	rf->deleteOnClose();
	return rf;
}

static void gxApkList(const std::string &fixedDirectory, const std::string &searchExt, FilenameList &filenameList, Bool searchSubdirectories)
{
	gxApkLoadIndex();
	if (s_gxApk == nullptr) return;
	std::string dir = gxApkNorm(fixedDirectory.c_str());
	if (dir == ".") dir.clear();
	if (!dir.empty() && dir.back() != '/') dir.push_back('/');
	std::string ext = gxApkNorm(searchExt.c_str());
	const bool all = ext.empty() || ext == ".*" || ext == "*";
	for (const auto &kv : *s_gxApk) {
		const std::string &k = kv.first;
		if (k.size() <= dir.size() || k.compare(0, dir.size(), dir) != 0) continue;
		const std::string rest = k.substr(dir.size());
		if (!searchSubdirectories && rest.find('/') != std::string::npos) continue;
		if (!all) {
			size_t dot = k.rfind('.');
			size_t sl = k.rfind('/');
			if (dot == std::string::npos || (sl != std::string::npos && dot < sl)) continue;
			if (k.compare(dot, std::string::npos, ext) != 0) continue;
		}
		AsciiString nf = kv.second.real.c_str();
		if (filenameList.find(nf) == filenameList.end()) {
			filenameList.insert(nf);
		}
	}
}

// Copies APK files under `prefix` (e.g. "fonts/") into the working directory.
// Only for libraries that open files by path themselves (FreeType fonts).
void GX_ApkExtractPrefix(const char *prefix)
{
	gxApkLoadIndex();
	if (s_gxApk == nullptr) return;
	const std::string pre = gxApkNorm(prefix);
	for (const auto &kv : *s_gxApk) {
		if (kv.first.compare(0, pre.size(), pre) != 0) continue;
		std::error_code ec;
		std::filesystem::path out(kv.second.real);
		if (std::filesystem::exists(out, ec) && std::filesystem::file_size(out, ec) == kv.second.size) continue;
		if (out.has_parent_path()) std::filesystem::create_directories(out.parent_path(), ec);
		char *d = nullptr; size_t n = 0;
		std::string full = std::string("GeneralsZH/") + kv.second.real;
		if (!g_gxApkRead(full.c_str(), &d, &n) || d == nullptr) continue;
		if (FILE *fp = fopen(kv.second.real.c_str(), "wb")) {
			fwrite(d, 1, n, fp);
			fclose(fp);
		}
		free(d);
	}
}

